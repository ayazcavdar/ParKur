  function parseInvokeError(err) {
    if (err == null) return t('ERR_GENERIC', { detail: 'unknown' });
    if (typeof err === 'object') {
      if (err.code) return t(err.code, err.params || {});
      if (err.message !== undefined) return parseInvokeError(err.message);
    }
    const raw = typeof err === 'string' ? err : String(err);
    try {
      const obj = JSON.parse(raw);
      if (obj.code) return t(obj.code, obj.params || {});
    } catch (_) { /* not JSON */ }
    if (raw.startsWith('ERR_')) {
      const [code, tail] = raw.split('|');
      const params = {};
      if (tail) tail.split(',').forEach((p) => { const i = p.indexOf('='); if (i > 0) params[p.slice(0, i)] = p.slice(i + 1); });
      return t(code, params);
    }
    return t('ERR_GENERIC', { detail: raw });
  }

