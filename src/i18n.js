  function fmt(template, params) {
    if (!template) return '';
    return template.replace(/\{(\w+)\}/g, (_, k) => (params && params[k] != null ? String(params[k]) : '{' + k + '}'));
  }

  function t(key, params) {
    const table = STR[uiLang] || STR.tr;
    const fall = STR.en[key] ? STR.en : STR.tr;
    const text = table[key] || fall[key] || key;
    return fmt(text, params || {});
  }

  function setUiLang(lang) {
    uiLang = lang === 'en' ? 'en' : 'tr';
    localStorage.setItem('parkur_ui_lang', uiLang);
    document.documentElement.lang = uiLang;
    document.title = t('app.title');
    if (typeof global.onParKurLangChange === 'function') global.onParKurLangChange();
  }

